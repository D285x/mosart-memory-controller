#!/usr/bin/env python3
"""Write results/mutation_results.md, mutation_results.csv and mutation_matrix.md from mutation/work/state.json."""
import json, os, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
muts = json.load(open(os.path.join(ROOT, 'mutation', 'work', 'state.json')))
R = os.path.join(ROOT, 'results')
os.makedirs(R, exist_ok=True)

def g(m, k, d=''):
    return m.get(k, d)

for m in muts:
    m['sim2'] = g(m, 'sim2', m['sim'])
valid = [m for m in muts if m['sim'] != 'INVALID']
equiv = [m for m in valid if str(g(m, 'equiv')).startswith('EQUIVALENT')]
nonequiv = [m for m in valid if m not in equiv]

def score(sel, key, val='KILLED'):
    k = sum(1 for m in sel if g(m, key) == val)
    return k, len(sel)

with open(os.path.join(R, 'mutation_results.csv'), 'w') as f:
    f.write('id,class,file,line,description,sim_v1,sim_v2,formal,formal_fsm,formal_cfg,formal_top,formal_latency,formal_time_s,equivalence\n')
    for m in muts:
        f.write(','.join('"%s"' % str(x).replace('"', "'") for x in (
            m['id'], m['cls'], m['file'], m['line'], m['desc'], m['sim'], m['sim2'], g(m, 'formal'),
            g(m, 'f_fsm'), g(m, 'f_cfg'), g(m, 'f_top'), g(m, 'f_lat'), g(m, 'f_time'), g(m, 'equiv'))) + '\n')

lines = ['# Mutation analysis', '',
         'Mutants are single-point changes to the RTL (`rtl/mem_ctrl_fsm.v`, `cfg_regs.v`, `sync_mem.v`, `mem_ctrl_top.v`): %d hand-written (class DIR) and %d generated by operator.' % (
             sum(1 for m in muts if m['cls'] == 'DIR'), sum(1 for m in muts if m['cls'] != 'DIR')),
         'Operator classes: ROR relational, LOR logical and bitwise, NEG negation, CNS constant, ARI arithmetic, IDX bit index, SDL statement deletion, STK output stuck-at, FSM state target.', '',
         '- Simulation v1: `tb/tb_mem_ctrl_param.v` before directed tests D1b and D13 (DATA_W 8, ADDR_W 4).',
         '- Simulation v2: the same testbench with D1b (power-up memory contents) and D13 (read data held) added.',
         '- Formal: SymbiYosys bounded model check of the block properties (FSM 30 cycles, configuration registers 25 cycles), then the exact-latency task (FSM mutants), then, for mutants still alive, the end-to-end property at DATA_W 2, ADDR_W 2, 12 cycles.',
         '- Equivalence: a Yosys SAT miter against the original controller (DATA_W 2, ADDR_W 3, 24 cycles, reset in the first cycle, all-zero initial state) for every mutant that survived simulation v1. "Equivalent" means no distinguishing input sequence exists within the bound. Mutants that only change the power-up value of the memory array cannot be judged by the miter, because the array is initialised to zero in both copies, and are marked INITIAL_STATE.', '']

k1, n = score(valid, 'sim')
k2, _ = score(valid, 'sim2')
kf, nf = score([m for m in valid if g(m, 'formal')], 'formal')
lines += ['## Summary', '', '| Measure | Killed | Total | Score |', '|---|---|---|---|']
lines.append('| Simulation v1, all valid mutants | %d | %d | %.1f %% |' % (k1, n, 100.0 * k1 / n))
lines.append('| Simulation v2, all valid mutants | %d | %d | %.1f %% |' % (k2, n, 100.0 * k2 / n))
if equiv:
    ka = sum(1 for m in nonequiv if m['sim2'] == 'KILLED')
    lines.append('| Simulation v2, excluding mutants shown equivalent | %d | %d | %.1f %% |' % (ka, len(nonequiv), 100.0 * ka / len(nonequiv)))
if nf:
    lines.append('| Formal property checks, all valid mutants | %d | %d | %.1f %% |' % (kf, nf, 100.0 * kf / nf))
    if equiv:
        kfe = sum(1 for m in nonequiv if g(m, 'formal') == 'KILLED')
        lines.append('| Formal property checks, excluding equivalent mutants | %d | %d | %.1f %% |' % (kfe, len(nonequiv), 100.0 * kfe / len(nonequiv)))
lines.append('')
lines.append('Mutants that failed to compile (stillborn, excluded): %d.  Mutants shown equivalent by the miter: %d.' % (len(muts) - len(valid), len(equiv)))

# per operator
lines += ['', '## By operator class', '', '| Class | Mutants | Equivalent | Sim v1 killed | Sim v2 killed | Formal killed |', '|---|---|---|---|---|---|']
byc = collections.OrderedDict()
for m in valid: byc.setdefault(m['cls'], []).append(m)
for c, ms in byc.items():
    lines.append('| %s | %d | %d | %d | %d | %d |' % (c, len(ms), sum(1 for m in ms if m in equiv),
        sum(1 for m in ms if m['sim'] == 'KILLED'), sum(1 for m in ms if m['sim2'] == 'KILLED'),
        sum(1 for m in ms if g(m, 'formal') == 'KILLED')))

# kill matrix categories
both = [m for m in nonequiv if m['sim2'] == 'KILLED' and g(m, 'formal') == 'KILLED']
simonly = [m for m in nonequiv if m['sim2'] == 'KILLED' and g(m, 'formal') != 'KILLED']
formonly = [m for m in nonequiv if m['sim2'] != 'KILLED' and g(m, 'formal') == 'KILLED']
neither = [m for m in nonequiv if m['sim2'] != 'KILLED' and g(m, 'formal') != 'KILLED']
lines += ['', '## Kill matrix (non-equivalent mutants)', '', '| | Formal kills | Formal survives |', '|---|---|---|',
          '| Simulation v2 kills | %d | %d |' % (len(both), len(simonly)),
          '| Simulation v2 survives | %d | %d |' % (len(formonly), len(neither)), '']

def listing(title, ms):
    out = ['### ' + title, '']
    if not ms: return out + ['None.', '']
    out += ['| ID | Class | File:line | Change | Sim v1 | Sim v2 | Formal |', '|---|---|---|---|---|---|---|']
    for m in ms:
        out.append('| %s | %s | %s:%s | %s | %s | %s | %s |' % (m['id'], m['cls'], m['file'], m['line'] or '-', m['desc'], m['sim'], m['sim2'], g(m, 'formal', 'n/a')))
    return out + ['']
lines += listing('Killed by formal only', formonly)
lines += listing('Killed by simulation only', simonly)
lines += listing('Survived both (need review)', neither)
lines += listing('Survived simulation v1 (all)', [m for m in valid if m['sim'] == 'SURVIVED'])
lines += ['### Equivalence results for simulation v1 survivors', '', '| ID | Change | Equivalence (miter) | Sim v2 |', '|---|---|---|---|']
for m in valid:
    if m['sim'] == 'SURVIVED':
        lines.append('| %s | %s | %s | %s |' % (m['id'], m['desc'], g(m, 'equiv', 'not run'), m['sim2']))
lines.append('')
ft = [g(m, 'f_time') for m in valid if g(m, 'f_time') != '']
if ft:
    lines.append('Formal run time per mutant: mean %.1f s, maximum %.1f s.' % (sum(ft) / len(ft), max(ft)))
open(os.path.join(R, 'mutation_results.md'), 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines[:40]))
