#!/usr/bin/env python3
"""Write results/<design>/mutation_results.md and mutation_results.csv from designs/<design>/mutation_work/state.json.
Same measures as mutation/report.py, plus the specification-equivalence column."""
import json, os, sys, collections, importlib.util
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
name = sys.argv[1]
DDIR = os.path.join(ROOT, 'designs', name)
spec = importlib.util.spec_from_file_location('design', os.path.join(DDIR, 'design.py'))
D = importlib.util.module_from_spec(spec); spec.loader.exec_module(D)
muts = json.load(open(os.path.join(DDIR, 'mutation_work', 'state.json')))
R = os.path.join(ROOT, 'results', name)
os.makedirs(R, exist_ok=True)

g = lambda m, k, d='': m.get(k, d)
for m in muts:
    m['sim2'] = g(m, 'sim2', m['sim'])
valid = [m for m in muts if m['sim'] != 'INVALID']


def eq_class(m):
    """EQ: no port difference within the bound; SPEC: differs only where the specification leaves the
    output undefined; PU: power-up only, equivalent from power-up within the bound; '' otherwise."""
    if str(g(m, 'equiv')).startswith('EQUIVALENT'):
        return 'EQ'
    if str(g(m, 'spec_equiv')).startswith('SPEC_EQUIVALENT'):
        return 'SPEC'
    if str(g(m, 'spec_equiv')).startswith('POWERUP_EQUIVALENT'):
        return 'PU'
    if m['id'] in getattr(D, 'ARGUED', {}):
        return 'ARG'
    return ''


equiv = [m for m in valid if eq_class(m)]
nonequiv = [m for m in valid if not eq_class(m)]
pct = lambda a, b: 100.0 * a / b if b else 0.0
cnt = lambda sel, key: sum(1 for m in sel if g(m, key) == 'KILLED')

with open(os.path.join(R, 'mutation_results.csv'), 'w') as f:
    f.write('id,class,file,line,description,sim_v1,sim_v2,formal,formal_bmc,formal_deep,formal_time_s,equivalence,spec_equivalence,equivalent_class\n')
    for m in muts:
        f.write(','.join('"%s"' % str(x).replace('"', "'") for x in (
            m['id'], m['cls'], m['file'], m['line'], m['desc'], m['sim'], m['sim2'], g(m, 'formal'),
            g(m, 'f_bmc'), g(m, 'f_deep'), g(m, 'f_time'), g(m, 'equiv'), g(m, 'spec_equiv'), eq_class(m))) + '\n')

L = ['# Mutation analysis: %s' % name, '',
     'Mutants: %d hand-written (class DIR) and %d generated by operator, in %s.' % (
         sum(1 for m in muts if m['cls'] == 'DIR'), sum(1 for m in muts if m['cls'] != 'DIR'), ', '.join('`rtl/%s`' % f for f in D.FILES)), '',
     '- Simulation v1: `%s` (frozen before any mutant was run).' % D.TB_V1[-1],
     '- Simulation v2: `%s` (v1 plus the tests added after analysing the v1 survivors).' % D.TB_V2[-1],
     '- Formal: %s.' % '; '.join('`%s` task %s' % (s, t) for s, t, _ in D.FORMAL + D.FORMAL_DEEP),
     '- Equivalence: port-level miter `%s` against the original for every v1 survivor (%s).' % (D.PORT_MITER, ', '.join(
         'depth %d%s' % (r['depth'], (' with ' + ', '.join('%s = %d' % kv for kv in r.get('params', {}).items())) if r.get('params') else '') for r in D.EQ_RUNS)),
     '- Specification equivalence: for miter-distinguishable survivors, `%s` compares only the specified behaviour (depth %d); power-up mutants use `%s`.' % (
         D.SPEC_MITER, D.SPEC_DEPTH, D.SPEC_MITER_PU), '']

k1, k2 = cnt(valid, 'sim'), cnt(valid, 'sim2')
kf = cnt(valid, 'formal')
L += ['## Summary', '', '| Measure | Killed | Total | Score |', '|---|---|---|---|',
      '| Simulation v1, all valid mutants | %d | %d | %.1f %% |' % (k1, len(valid), pct(k1, len(valid))),
      '| Simulation v2, all valid mutants | %d | %d | %.1f %% |' % (k2, len(valid), pct(k2, len(valid))),
      '| Simulation v1, excluding equivalent mutants | %d | %d | %.1f %% |' % (cnt(nonequiv, 'sim'), len(nonequiv), pct(cnt(nonequiv, 'sim'), len(nonequiv))),
      '| Simulation v2, excluding equivalent mutants | %d | %d | %.1f %% |' % (cnt(nonequiv, 'sim2'), len(nonequiv), pct(cnt(nonequiv, 'sim2'), len(nonequiv))),
      '| Formal property checks, all valid mutants | %d | %d | %.1f %% |' % (kf, len(valid), pct(kf, len(valid))),
      '| Formal property checks, excluding equivalent mutants | %d | %d | %.1f %% |' % (cnt(nonequiv, 'formal'), len(nonequiv), pct(cnt(nonequiv, 'formal'), len(nonequiv))), '']
ec = collections.Counter(eq_class(m) for m in equiv)
L.append('Stillborn (do not compile): %d. Equivalent: %d (port-level %d, specification-level %d, power-up only %d, argued %d).' % (
    len(muts) - len(valid), len(equiv), ec['EQ'], ec['SPEC'], ec['PU'], ec['ARG']))
arg = [m for m in valid if eq_class(m) == 'ARG']
if arg:
    ne2 = nonequiv + arg
    L.append('Counting the argued mutants as non-equivalent instead: simulation v2 %d of %d, formal %d of %d.' % (
        cnt(ne2, 'sim2'), len(ne2), cnt(ne2, 'formal'), len(ne2)))
    L += ['', 'Argued equivalent (tool-distinguishable, but within the specification):', '']
    for m in arg:
        L.append('- %s (%s): %s.' % (m['id'], m['desc'], D.ARGUED[m['id']]))
to = [m['id'] for m in valid if 'TIMEOUT' in (g(m, 'f_bmc'), g(m, 'f_deep'))]
if to:
    L.append('Formal runs that hit the time limit (counted as not killed): %s.' % ', '.join(to))

L += ['', '## By operator class', '', '| Class | Mutants | Equivalent | Sim v1 killed | Sim v2 killed | Formal killed |', '|---|---|---|---|---|---|']
byc = collections.OrderedDict()
for m in valid: byc.setdefault(m['cls'], []).append(m)
for c, ms in byc.items():
    L.append('| %s | %d | %d | %d | %d | %d |' % (c, len(ms), sum(1 for m in ms if eq_class(m)), cnt(ms, 'sim'), cnt(ms, 'sim2'), cnt(ms, 'formal')))

L += ['', '## Kill matrix (non-equivalent mutants)', '']
for key, lab in (('sim', 'Simulation v1'), ('sim2', 'Simulation v2')):
    a = sum(1 for m in nonequiv if g(m, key) == 'KILLED' and g(m, 'formal') == 'KILLED')
    b = sum(1 for m in nonequiv if g(m, key) == 'KILLED' and g(m, 'formal') != 'KILLED')
    c = sum(1 for m in nonequiv if g(m, key) != 'KILLED' and g(m, 'formal') == 'KILLED')
    d = sum(1 for m in nonequiv if g(m, key) != 'KILLED' and g(m, 'formal') != 'KILLED')
    L += ['| %s | Formal kills | Formal survives |' % lab, '|---|---|---|',
          '| Simulation kills | %d | %d |' % (a, b), '| Simulation survives | %d | %d |' % (c, d), '']


def table(sel, title):
    out = ['### ' + title, '']
    if not sel:
        return out + ['None.', '']
    out += ['| ID | Class | File:line | Change | Sim v1 | Sim v2 | Formal | Equivalence | Spec. equivalence | Class |', '|---|---|---|---|---|---|---|---|---|---|']
    for m in sel:
        out.append('| %s | %s | %s:%s | %s | %s | %s | %s | %s | %s | %s |' % (m['id'], m['cls'], m['file'], m['line'] or '-', m['desc'],
                   m['sim'], m['sim2'], g(m, 'formal'), g(m, 'equiv', '-'), g(m, 'spec_equiv', '-'), eq_class(m) or 'real'))
    return out + ['']

L += table([m for m in valid if m['sim'] == 'SURVIVED'], 'All survivors of simulation v1')
L += table([m for m in nonequiv if g(m, 'formal') == 'KILLED' and m['sim'] != 'KILLED'], 'Killed by formal but not by simulation v1')
L += table([m for m in nonequiv if g(m, 'formal') != 'KILLED' and m['sim2'] == 'KILLED'], 'Killed by simulation v2 but not by formal')
L += table([m for m in nonequiv if g(m, 'formal') != 'KILLED' and m['sim2'] != 'KILLED'], 'Non-equivalent, survived simulation v2 and formal')
open(os.path.join(R, 'mutation_results.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L[:40]))
